/** One job of an exec spec (mirrors schema/job.schema.json). */
export interface ExecItem {
  input: string;
  output: string;
  preset?: string;
  size?: [number, number];
  mode?: Mode;
  format?: FormatOption;
  quality?: number;
  position?: CropPosition;
  focalPoint?: Point;
  background?: string;
  smallInput?: SmallInputPolicy;
  upscale?: boolean;
  sharpen?: number;
  stripMetadata?: boolean;
  png?: { compressionLevel?: number; palette?: boolean };
  jpeg?: { progressive?: boolean };
}

export interface ExecSpec {
  schemaVersion: 1;
  config?: string;
  root?: string;
  onConflict?: OnConflict;
  concurrency?: number;
  dryRun?: boolean;
  jobs: ExecItem[];
}

export interface ExecOptions {
  cwd?: string;
  signal?: AbortSignal;
  onEvent?: (event: ProgressEvent) => void;
}

/** Inline options that may override a preset, in the order they are applied. */
const OVERRIDES = ["mode", "format", "quality", "position", "focalPoint", "background", "smallInput", "upscale", "sharpen", "stripMetadata", "png", "jpeg"] as const;

/** Parses + validates job JSON (schema/job.schema.json). */
export async function parseExecSpec(text: string): Promise<ExecSpec> {
  let data: unknown;
  try {
    data = JSON.parse(text.replace(/^﻿/, ""));
  } catch (err) {
    throw new ImgfitError("E_USAGE", `Job không phải JSON hợp lệ: ${(err as Error).message}`);
  }
  return validateWith<ExecSpec>("job", data, "Job", "E_USAGE");
}

/** Preset (if any) overlaid with the item's inline options. Throws on invalid combinations. */
function transformFor(item: ExecItem, cfg: PresetConfigSet | undefined): TransformOptions {
  const base = item.preset ? cfg?.presets.get(item.preset)?.transform : undefined;
  if (item.preset && !base) throw new ImgfitError("E_USAGE", `Preset "${item.preset}" không có trong config`);
  const size = item.size ?? (base ? [base.width, base.height] : undefined);
  if (!size) throw new ImgfitError("E_USAGE", "Job cần preset hoặc size");
  const t: TransformOptions = { ...(base ?? { mode: "fit", format: "keep" }), width: size[0], height: size[1] } as TransformOptions;
  for (const k of OVERRIDES) if (item[k] !== undefined) Object.assign(t, { [k]: item[k] });
  if (t.focalPoint && !item.position) t.position = "focal";
  validateTransformOptions(t);
  return t;
}

/**
 * `imgfit exec`: runs an explicit job list (input → output) generated by another program.
 * Same engine as resize: a collision aborts the batch; existing files are kept unless onConflict=replace.
 */
export async function exec(spec: ExecSpec, opts: ExecOptions = {}): Promise<Report> {
  const startedAt = new Date();
  const cwd = path.resolve(opts.cwd ?? process.cwd());
  const root = path.resolve(cwd, spec.root ?? ".");
  const cfg = spec.jobs.some((j) => j.preset) ? await loadConfig(await findConfig(cwd, spec.config)) : undefined;

  const jobs: Job[] = spec.jobs.map((item) => {
    const source = path.resolve(cwd, item.input);
    const result = newFileResult(displayPath(cwd, source), { preset: item.preset ?? null });
    let transform: TransformOptions = { width: 1, height: 1, mode: "fit", format: "keep" };
    try {
      transform = transformFor(item, cfg);
    } catch (err) {
      fail(result, err);
    }
    return { source, transform, result, meta: { output: item.output } };
  });

  const limit = pLimit(spec.concurrency ?? 4);
  await Promise.all(
    jobs.map((j) =>
      limit(async () => {
        if (j.result.status === "failed") return;
        await prepareJob(j);
        if ((j.result.status as string) !== "planned" || !j.plan) return;
        try {
          const dest = path.resolve(cwd, j.meta?.output as string);
          j.result.destination = displayPath(cwd, dest);
          if (!isInside(root, dest)) throw new ImgfitError("E_PATH_UNSAFE", `Output nằm ngoài root ${displayPath(cwd, root)}: ${j.result.destination}`);
          assertExtension(dest, j.plan.outputFormat, j.result.destination);
          j.dest = dest;
        } catch (err) {
          fail(j.result, err);
        }
      }),
    ),
  );

  return executeJobs("exec", startedAt, jobs, {
    outputRoot: root,
    onConflict: spec.onConflict ?? "error",
    concurrency: spec.concurrency ?? 4,
    dryRun: spec.dryRun ?? false,
    backup: false,
    backupRoot: path.join(cwd, ".imgfit", "backups"),
    ...(opts.signal ? { signal: opts.signal } : {}),
    ...(opts.onEvent ? { onEvent: opts.onEvent } : {}),
  });
}
